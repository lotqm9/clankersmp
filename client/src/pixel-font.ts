export const FONT_HEIGHT = 8;

const glyph = (ch: string) => G[ch] ?? G["?"];

/** Width of a text in GUI pixels (1 pixel between letters). */
export function textWidth(text: string): number {
  let w = 0;
  for (const ch of text) w += glyph(ch)[0].length + 1;
  return Math.max(0, w - 1);
}

/** Draw a text at (x, y) (top of the letters) on a 1-GUI-pixel canvas; a shadow goes 1 pixel down and right. */
export function drawText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, color: string, shadow: string | null = null): void {
  const pass = (ox: number, oy: number, col: string) => {
    ctx.fillStyle = col;
    let cx = x + ox;
    for (const ch of text) {
      const g = glyph(ch);
      for (let r = 0; r < g.length; r++) for (let c = 0; c < g[r].length; c++) if (g[r][c] === "#") ctx.fillRect(cx + c, y + oy + r, 1, 1);
      cx += g[0].length + 1;
    }
  };
  if (shadow) pass(1, 1, shadow);
  pass(0, 0, color);
}

const cache = new Map<string, string>();

/** A text as a data URL image at 1 GUI pixel per font pixel (with room for the shadow). */
export function textImage(text: string, color: string, shadow: string | null = null): { url: string; w: number; h: number } {
  const w = textWidth(text) + (shadow ? 1 : 0);
  const h = FONT_HEIGHT + (shadow ? 1 : 0);
  const key = `${text}|${color}|${shadow}`;
  let url = cache.get(key);
  if (!url) {
    const c = document.createElement("canvas");
    c.width = Math.max(1, w);
    c.height = h;
    drawText(c.getContext("2d")!, text, 0, 0, color, shadow);
    url = c.toDataURL();
    cache.set(key, url);
  }
  return { url, w, h };
}

/** A pixel-text element sized in GUI pixels (var(--s) per pixel), crisp at any GUI scale. */
export function textEl(text: string, color: string, shadow: string | null = null, cls = "ptext"): HTMLDivElement {
  const t = textImage(text, color, shadow);
  const d = document.createElement("div");
  d.className = cls;
  d.style.width = `calc(var(--s) * ${t.w})`;
  d.style.height = `calc(var(--s) * ${t.h})`;
  d.style.backgroundImage = `url(${t.url})`;
  return d;
}
